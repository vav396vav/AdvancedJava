//    indexOf(String str) и indexOf(char c) -- получают индекс вхождения строки или символа;
//    substring(int beginIndex) и substring(int beginIndex, int endIndex) --получают подстроку по индексам;
//    equalsIgnoreCase(String another) --сравнивает строки без учёта регистра;
//    split(String regex) и split(String regex, int limit) -- разделяют строку и получают массив элементов;
//    isEmpty() -- проверяет, является ли строка пустой;
//    contains(String s) -- проверяет, существует ли строка s в текущей;
//    startsWith(String prefix) и endsWith(String suffix)-- проверяют, существует ли строка в начале или в конце текущей;
//    toLowerCase() и toUpperCase() -- переводят все буквенные символы в нижний или верхний регистр соответственно.
